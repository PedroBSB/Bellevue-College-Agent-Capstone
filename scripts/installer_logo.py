"""Write the app's Bulldog badge (bcagent/ui.py) into install.sh and install.ps1, so the installers
show the same logo. Run after changing the logo:  python scripts/installer_logo.py"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from bcagent.ui import installer_logo  # noqa: E402

BEGIN = "# >>> bulldog logo data: generated by scripts/installer_logo.py from bcagent/ui.py - do not edit"
END = "# <<< bulldog logo data"


def block(kind: str) -> str:
    blue, palette, rows = installer_logo()
    body = "\n".join(rows)
    if kind == "sh":
        data = f"LOGO_BLUE='{blue}'\nLOGO_PALETTE='{palette}'\nLOGO_ROWS='\n{body}\n'"
    else:
        data = f"$LogoBlue = '{blue}'\n$LogoPalette = '{palette}'\n$LogoRows = @'\n{body}\n'@"
    return f"{BEGIN}\n{data}\n{END}"


def updated(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    new, n = re.subn(re.escape(BEGIN) + r".*?" + re.escape(END),
                     lambda _: block("sh" if path.suffix == ".sh" else "ps1"), text, flags=re.S)
    if n != 1:
        raise SystemExit(f"{path.name}: logo markers not found")
    return new


if __name__ == "__main__":
    for name in ("install.sh", "install.ps1"):
        f = ROOT / name
        new = updated(f)
        if new != f.read_text(encoding="utf-8"):
            f.write_bytes(new.encode("utf-8"))
            print(f"updated {name}")

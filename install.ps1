function Banner {
  $color = $env:FORCE_COLOR -or ($Host.UI.SupportsVirtualTerminal -and -not [Console]::IsOutputRedirected)
  if (-not $color -or $env:NO_COLOR) {
    Write-Host ""
    Write-Host "bcagent installer - BELLEVUE COLLEGE" -ForegroundColor Blue
    Write-Host ""
    return
  }
  $e = [char]27; $r = "$e[0m"
  $pal = @($LogoPalette -split ' ' | ForEach-Object { "2;" + ($_ -split ':')[0] })   # "r;g;b:n" -> truecolor
  $blue = "2;" + ($LogoBlue -split ':')[0]
  $rows = @($LogoRows -split "`r?`n" | Where-Object { $_ })
  $n = [int]($rows[0].Length / 2)
  $up = [string][char]0x2580; $down = [string][char]0x2584; $bar = [string][char]0x2502; $h = [string][char]0x2500
  $b = "$e[38;${blue}m"; $bb = "$e[1;38;${blue}m"
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append("`n$b" + [char]0x256D + ($h * ($n + 2)) + [char]0x256E + "$r`n")
  for ($i = 0; $i -lt $rows.Count; $i += 2) {   # one text line = two pixel rows: top half, bottom half
    [void]$sb.Append("$b$bar$r ")
    for ($x = 0; $x -lt $n; $x++) {
      $t = $rows[$i].Substring($x * 2, 2); $d = $rows[$i + 1].Substring($x * 2, 2)
      if ($t -ne '..' -and $d -ne '..') { [void]$sb.Append("$e[38;$($pal[[int]$t]);48;$($pal[[int]$d])m$up$r") }
      elseif ($t -ne '..') { [void]$sb.Append("$e[38;$($pal[[int]$t])m$up$r") }
      elseif ($d -ne '..') { [void]$sb.Append("$e[38;$($pal[[int]$d])m$down$r") }
      else { [void]$sb.Append(' ') }
    }
    [void]$sb.Append(" $b$bar$r`n")
  }
  $pad = [int][math]::Floor(($n - 16) / 2)
  [void]$sb.Append("$b$bar" + (' ' * ($n + 2)) + "$bar$r`n")
  [void]$sb.Append("$b$bar$r $bb" + (' ' * $pad) + "BELLEVUE COLLEGE" + (' ' * ($n - 16 - $pad)) + "$r $b$bar$r`n")
  [void]$sb.Append("$b" + [char]0x2570 + ($h * ($n + 2)) + [char]0x256F + "$r`n")
  [void]$sb.Append("$bb  bcagent installer$r`n")
  Write-Host $sb.ToString()
}

